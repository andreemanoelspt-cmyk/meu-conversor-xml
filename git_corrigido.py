def classificar_regra_construcao_operacao_6(segmento, cfop, ncm_valor, descricao, icms_grupo):
    if not segmento_eh_material_construcao(segmento):
        return "nenhum", None

    cfop = (cfop or "").strip()
    ncm_valor = normalizar_ncm_codigo(ncm_valor)
    if not ncm_valor:
        return "nenhum", None

    tem_icms_normal = item_tem_icms_normal_destacado(icms_grupo)
    tem_icms_ou_st = item_tem_icms_normal_ou_st_destacado(icms_grupo)

    # Lista específica informada: mantém ICMS em 6101-6109, 6401-6409 e 6910.
    # Exceção: ICMS normal + match somente por prefixo de 4 a 6 dígitos vai para verificação.
    if cfop_regra_construcao_verificacao(cfop) and tem_icms_ou_st:
        prefixo = melhor_match_lista_construcao_manter_icms(ncm_valor)
        if prefixo:
            if tem_icms_normal and 4 <= len(prefixo) <= 6 and ncm_valor != prefixo:
                return "confirmar", MOTIVO_CONFIRMACAO_CONSTRUCAO_PREFIXO_ICMS_NORMAL
            return "manter", None

    # Listas internas por número de dígitos: zera automático, sem confirmação.
    if aplicar_regras_novas(ncm_valor):
        return "zerar_auto", "Regra 1"

    # Similaridade: manda para confirmação com o motivo solicitado.
    if similaridade_60_palavras_chave(descricao):
        return "confirmar", MOTIVO_CONFIRMACAO_CONSTRUCAO_SIMILARIDADE

    # CFOP em lista de exceção: manda para confirmação.
    if cfop in cfop_excecoes:
        return "confirmar", MOTIVO_CONFIRMACAO_CONSTRUCAO_EXCECAO

    return "nenhum", None


