def item_tem_icms_st_destacado(icms_grupo):
    """
    Identifica ST destacada/retida no grupo ICMS por campos usuais da NF-e.
    Basta algum valor de ST ser maior que zero.
    """
    if icms_grupo is None:
        return False
    campos_st = {
        "vBCST", "vICMSST", "vBCSTRet", "vICMSSTRet",
        "vICMSSubstituto", "vBCFCPST", "vFCPST", "vBCFCPSTRet", "vFCPSTRet",
    }
    for grupo in list(icms_grupo):
        for filho in list(grupo):
            nome = filho.tag.split("}")[-1]
            if nome in campos_st and parse_float(filho.text or "0") > 0:
                return True
    return False


