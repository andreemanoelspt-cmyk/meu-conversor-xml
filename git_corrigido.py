def coletar_itens_construcao_verificacao(arquivos_xml, segmento):
    itens = []
    vistos = set()

    if not segmento_eh_material_construcao(segmento):
        return itens

    for caminho in arquivos_xml:
        try:
            tree_xml = ET.parse(caminho)
            root = tree_xml.getroot()
        except Exception:
            continue

        infnfe = root.find(".//nfe:infNFe", ns)
        chave_nfe = infnfe.attrib.get("Id", "").replace("NFe", "") if infnfe is not None else ""
        numero_nf = root.findtext(".//nfe:ide/nfe:nNF", default="", namespaces=ns)

        for det in root.findall(".//nfe:det", ns):
            ncm_el = det.find(".//nfe:NCM", ns)
            xprod_el = det.find(".//nfe:xProd", ns)
            cfop_el = det.find(".//nfe:CFOP", ns)
            vprod_el = det.find(".//nfe:vProd", ns)
            icms_grupo = det.find(".//nfe:ICMS", ns)

            ncm_val = ncm_el.text.strip() if ncm_el is not None and ncm_el.text else ""
            xprod_val = xprod_el.text.strip() if xprod_el is not None and xprod_el.text else ""
            cfop_val = cfop_el.text.strip() if cfop_el is not None and cfop_el.text else ""
            vprod_val = vprod_el.text.strip() if vprod_el is not None and vprod_el.text else ""

            acao, motivo = classificar_regra_construcao_operacao_6(segmento, cfop_val, ncm_val, xprod_val, icms_grupo)
            if acao != "confirmar":
                continue

            chave_item = montar_chave_item(caminho, det, ncm_val, xprod_val, cfop_val)
            if chave_item in vistos:
                continue
            vistos.add(chave_item)

            itens.append({
                "chave": chave_item,
                "arquivo": os.path.basename(caminho),
                "numero_nf": numero_nf,
                "chave_nfe": chave_nfe,
                "item": det.attrib.get("nItem", ""),
                "xprod": xprod_val,
                "ncm": ncm_val,
                "cfop": cfop_val,
                "vprod": vprod_val,
                "motivo": motivo or "Verificação - material de construção",
            })

    return itens


