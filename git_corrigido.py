def _parse_data_emissao_relatorio(valor):
    if not valor:
        return ""
    try:
        data_part = valor.split('T')[0]
        return datetime.strptime(data_part, "%Y-%m-%d").strftime("%d/%m/%Y")
    except Exception:
        return valor


def extrair_dados_relatorio_de_arquivo_xml(caminho_xml):
    try:
        tree = ET.parse(caminho_xml)
        root = tree.getroot()

        infNFe = root.find('.//nfe:infNFe', ns)
        ide = root.find('.//nfe:ide', ns)
        emit = root.find('.//nfe:emit', ns)
        dest = root.find('.//nfe:dest', ns)

        chave = (infNFe.attrib.get('Id', '') if infNFe is not None else '').replace('NFe', '')
        numero = ide.findtext('nfe:nNF', default='', namespaces=ns) if ide is not None else ''
        data = _parse_data_emissao_relatorio(ide.findtext('nfe:dhEmi', default='', namespaces=ns) if ide is not None else '')

        nome_emit = emit.findtext('nfe:xNome', default='', namespaces=ns) if emit is not None else ''
        uf_emit = emit.findtext('.//nfe:UF', default='', namespaces=ns) if emit is not None else ''

        nome_dest = dest.findtext('nfe:xNome', default='', namespaces=ns) if dest is not None else ''
        uf_dest = dest.findtext('.//nfe:UF', default='', namespaces=ns) if dest is not None else ''
        ie_dest = dest.findtext('nfe:IE', default='', namespaces=ns) if dest is not None else ''

        cnpj_cpf_dest = ''
        if dest is not None:
            cnpj_cpf_dest = dest.findtext('nfe:CNPJ', default='', namespaces=ns)
            if not cnpj_cpf_dest:
                cnpj_cpf_dest = dest.findtext('nfe:CPF', default='', namespaces=ns)

        valor_total_nf = parse_float(root.findtext('.//nfe:ICMSTot/nfe:vNF', default='0.00', namespaces=ns))
        info_compl = root.findtext('.//nfe:infAdic/nfe:infCpl', default='', namespaces=ns)
        info_compl = info_compl.replace('\n', ' ').replace('\r', ' ').strip() if info_compl else ''

        linhas = []
        for det in root.findall('.//nfe:det', ns):
            prod = det.find('nfe:prod', ns)
            imposto = det.find('nfe:imposto', ns)
            if prod is None:
                continue

            nome_prod = prod.findtext('nfe:xProd', default='', namespaces=ns)
            ncm = prod.findtext('nfe:NCM', default='', namespaces=ns)
            cfop = prod.findtext('nfe:CFOP', default='', namespaces=ns)
            valor_prod = parse_float(prod.findtext('nfe:vProd', default='0.00', namespaces=ns))
            valor_frete = parse_float(prod.findtext('nfe:vFrete', default='0.00', namespaces=ns))
            valor_desc = parse_float(prod.findtext('nfe:vDesc', default='0.00', namespaces=ns))
            valor_outro = parse_float(prod.findtext('nfe:vOutro', default='0.00', namespaces=ns))
            valor_ipi = parse_float(imposto.findtext('.//nfe:IPI//nfe:vIPI', default='0.00', namespaces=ns)) if imposto is not None else 0.0

            cst_icms = ''
            base_icms = 0.0
            aliq_icms = 0.0
            valor_icms = 0.0
            valor_icms_st = 0.0

            icms_node = imposto.find('nfe:ICMS', ns) if imposto is not None else None
            if icms_node is not None:
                for child in list(icms_node):
                    cst_tag = child.findtext('nfe:CST', default='', namespaces=ns)
                    csosn_tag = child.findtext('nfe:CSOSN', default='', namespaces=ns)
                    if cst_tag:
                        cst_icms = cst_tag
                    elif csosn_tag:
                        cst_icms = csosn_tag

                    vbc_temp = child.findtext('nfe:vBC', default=None, namespaces=ns)
                    picms_temp = child.findtext('nfe:pICMS', default=None, namespaces=ns)
                    vicms_temp = child.findtext('nfe:vICMS', default=None, namespaces=ns)
                    vicmsst_temp = child.findtext('nfe:vICMSST', default=None, namespaces=ns)

                    if vbc_temp is not None:
                        base_icms = parse_float(vbc_temp)
                    if picms_temp is not None:
                        aliq_icms = parse_float(picms_temp)
                    if vicms_temp is not None:
                        valor_icms = parse_float(vicms_temp)
                    if vicmsst_temp is not None:
                        valor_icms_st = parse_float(vicmsst_temp)

                    if cst_icms:
                        break

            linhas.append({
                'Arquivo XML': os.path.basename(caminho_xml),
                'Número NF': numero,
                'Chave Acesso': chave,
                'Data Emissão': data,
                'Emitente': nome_emit,
                'UF Origem': uf_emit,
                'Destinatário': nome_dest,
                'CNPJ/CPF Destinatário': cnpj_cpf_dest,
                'IE Destinatário': ie_dest,
                'UF Destino': uf_dest,
                'Valor Total NF': valor_total_nf,
                'Produto': nome_prod,
                'NCM': ncm,
                'CFOP': cfop,
                'CST ICMS': cst_icms,
                'Valor Produto': valor_prod,
                'Valor Frete': valor_frete,
                'Valor Desconto': valor_desc,
                'Outras Despesas': valor_outro,
                'Valor IPI': valor_ipi,
                'Base ICMS': base_icms,
                'Alíquota ICMS (%)': aliq_icms,
                'Valor ICMS': valor_icms,
                'Valor ICMS ST': valor_icms_st,
                'Informações Complementares': info_compl,
            })

        return linhas
    except Exception:
        return []


def gerar_relatorio_fiscal_xmls_modificados(xml_paths, pasta_saida):
    dados = []
    for caminho_xml in xml_paths:
        dados.extend(extrair_dados_relatorio_de_arquivo_xml(caminho_xml))

    if not dados:
        return None

    df = pd.DataFrame(dados)
    colunas_ordenadas = [
        'Arquivo XML', 'Número NF', 'Chave Acesso', 'Data Emissão', 'Emitente', 'UF Origem',
        'Destinatário', 'CNPJ/CPF Destinatário', 'IE Destinatário', 'UF Destino',
        'Valor Total NF', 'Produto', 'NCM', 'CFOP', 'CST ICMS', 'Valor Produto',
        'Valor Frete', 'Valor Desconto', 'Outras Despesas', 'Valor IPI', 'Base ICMS',
        'Alíquota ICMS (%)', 'Valor ICMS', 'Valor ICMS ST', 'Informações Complementares'
    ]
    cols_existentes = [c for c in colunas_ordenadas if c in df.columns]
    restante = [c for c in df.columns if c not in cols_existentes]
    df = df[cols_existentes + restante]

    caminho_relatorio = os.path.join(
        pasta_saida,
        f"relatorio_fiscal_xmls_modificados_{datetime.now().strftime('%Y%m%d_%H%M%S')}.xlsx",
    )
    df.to_excel(caminho_relatorio, index=False)
    return caminho_relatorio


