# CFOPs que podem aparecer na tela de definição de uso e consumo.
# A tela manual ficará restrita a estes intervalos:
# 5101 a 5109, 5401 a 5409, 6101 a 6109 e 6401 a 6409.
CFOPS_TELA_USO_CONSUMO = (
    {str(c) for c in range(5101, 5110)}
    | {str(c) for c in range(5401, 5410)}
    | {str(c) for c in range(6101, 6110)}
    | {str(c) for c in range(6401, 6410)}
)


def cfop_permitido_tela_uso_consumo(cfop):
    cfop = (cfop or "").strip()
    return cfop in CFOPS_TELA_USO_CONSUMO


def coletar_itens_pendentes(arquivos_xml, segmento):
    itens_pendentes = []
    vistos = set()
    ncms_conhecidos = NCM_POR_SEGMENTO.get(segmento, set())

    for caminho in arquivos_xml:
        try:
            tree_xml = ET.parse(caminho)
            root = tree_xml.getroot()
        except Exception:
            continue

        infnfe = root.find(".//nfe:infNFe", ns)
        chave_nfe = infnfe.attrib.get("Id", "").replace("NFe", "") if infnfe is not None else ""
        numero_nf = root.findtext(".//nfe:ide/nfe:nNF", default="", namespaces=ns)

        for det in root.findall(".//nfe:det", ns):
            ncm_el = det.find(".//nfe:NCM", ns)
            xprod_el = det.find(".//nfe:xProd", ns)
            cfop_el = det.find(".//nfe:CFOP", ns)
            vprod_el = det.find(".//nfe:vProd", ns)

            ncm_val = ncm_el.text.strip() if ncm_el is not None and ncm_el.text else ""
            xprod_val = xprod_el.text.strip() if xprod_el is not None and xprod_el.text else ""
            cfop_val = cfop_el.text.strip() if cfop_el is not None and cfop_el.text else ""
            vprod_val = vprod_el.text.strip() if vprod_el is not None and vprod_el.text else ""

            if not xprod_val:
                continue

            # NOVA REGRA:
            # A tela de definição de uso/consumo só exibe os CFOPs:
            # 5101-5109, 5401-5409, 6101-6109 e 6401-6409.
            if not cfop_permitido_tela_uso_consumo(cfop_val):
                continue

            # Se o NCM já consta nas listas do segmento ou nas regras prioritárias,
            # o programa não pergunta manualmente, pois as regras automáticas já tratam.
            if ncm_val in ncms_conhecidos:
                continue
            if ncm_val and verificar_regras_prioritarias(ncm_val, xprod_val):
                continue

            chave_item = montar_chave_item(caminho, det, ncm_val, xprod_val, cfop_val)
            if chave_item in vistos:
                continue
            vistos.add(chave_item)

            itens_pendentes.append({
                "chave": chave_item,
                "arquivo": os.path.basename(caminho),
                "numero_nf": numero_nf,
                "chave_nfe": chave_nfe,
                "item": det.attrib.get("nItem", ""),
                "xprod": xprod_val,
                "ncm": ncm_val,
                "cfop": cfop_val,
                "vprod": vprod_val,
            })

    return itens_pendentes


