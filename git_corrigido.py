def sort_treeview(treeview, col, reverse):
    dados = [(treeview.set(k, col), k) for k in treeview.get_children("")]
    try:
        dados.sort(key=lambda x: float(str(x[0]).replace(",", ".")), reverse=reverse)
    except Exception:
        dados.sort(key=lambda x: str(x[0]).lower(), reverse=reverse)

    for idx, (_, item_id) in enumerate(dados):
        treeview.move(item_id, "", idx)

    treeview.heading(col, command=lambda: sort_treeview(treeview, col, not reverse))


