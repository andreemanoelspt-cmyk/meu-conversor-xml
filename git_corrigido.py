def normalizar_texto_similaridade(texto):
    texto = (texto or "").upper()
    substituicoes = {
        "Á": "A", "À": "A", "Â": "A", "Ã": "A",
        "É": "E", "Ê": "E",
        "Í": "I",
        "Ó": "O", "Ô": "O", "Õ": "O",
        "Ú": "U",
        "Ç": "C",
    }
    for antigo, novo in substituicoes.items():
        texto = texto.replace(antigo, novo)
    return " ".join(texto.split())


@functools.lru_cache(maxsize=8192)
def similaridade_60_palavras_chave(descricao):
    """
    Compara a descrição com as palavras-chave usando difflib.SequenceMatcher.
    Considera compatível quando a proporção de caracteres semelhantes for >= 60%.
    Cache via lru_cache para evitar recalcular a mesma descrição.
    """
    desc = normalizar_texto_similaridade(descricao)
    if not desc:
        return False
    for palavra in palavras_chave_similares:
        chave = normalizar_texto_similaridade(palavra)
        if not chave:
            continue
        if chave in desc or desc in chave:
            return True
        if difflib.SequenceMatcher(None, desc, chave).ratio() >= 0.60:
            return True
    return False


