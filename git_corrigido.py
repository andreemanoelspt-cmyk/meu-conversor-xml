def aplicar_escolhas_manuais_em_arquivo(caminho_arquivo, pasta_saida, modificados, escolhas_uso_consumo):
    tree = ET.parse(caminho_arquivo)
    root = tree.getroot()
    infnfe = root.find(".//nfe:infNFe", ns)
    chave_nfe = infnfe.attrib.get("Id", "").replace("NFe", "") if infnfe is not None else ""
    numero_nf = root.findtext(".//nfe:ide/nfe:nNF", namespaces=ns)

    houve_alteracao_manual = False

    for det in root.findall(".//nfe:det", ns):
        ncm_el = det.find(".//nfe:NCM", ns)
        xprod_el = det.find(".//nfe:xProd", ns)
        cfop_el = det.find(".//nfe:CFOP", ns)
        vprod_el = det.find(".//nfe:vProd", ns)
        icms_container = det.find(".//nfe:ICMS", ns)

        ncm_val = ncm_el.text.strip() if ncm_el is not None and ncm_el.text else ""
        xprod_val = xprod_el.text.strip() if xprod_el is not None and xprod_el.text else ""
        cfop_antes = cfop_el.text.strip() if cfop_el is not None and cfop_el.text else ""
        vprod_val = vprod_el.text.strip() if vprod_el is not None and vprod_el.text else ""

        chave_item = montar_chave_item(caminho_arquivo, det, ncm_val, xprod_val, cfop_antes)
        escolha = escolhas_uso_consumo.get(chave_item, {"cfop": None, "zerar_icms": False})

        if not escolha.get("cfop"):
            continue

        novo_cfop = normalizar_cfop_manual(cfop_antes, escolha["cfop"])
        if cfop_el is not None:
            cfop_el.text = novo_cfop

        vbc_antes = "0.00"
        vicms_antes = "0.00"
        if icms_container is not None and escolha.get("zerar_icms"):
            for grupo in list(icms_container):
                vbc = grupo.find("nfe:vBC", ns)
                vicms = grupo.find("nfe:vICMS", ns)
                if vbc is not None and (vbc.text or "").strip():
                    vbc_antes = vbc.text
                if vicms is not None and (vicms.text or "").strip():
                    vicms_antes = vicms.text
                zerar_campos(grupo)

        modificados.append({
            "Número NF": numero_nf,
            "Chave NF-e": chave_nfe,
            "Arquivo": os.path.basename(caminho_arquivo),
            "Item": det.attrib.get("nItem", ""),
            "Produto": xprod_val,
            "Valor Produto": vprod_val,
            "NCM": ncm_val,
            "CFOP Antes": cfop_antes,
            "CFOP Depois": novo_cfop,
            "vBC Antes": vbc_antes,
            "vICMS Antes": vicms_antes,
            "vBC Depois": "0.00" if escolha.get("zerar_icms") else "",
            "vICMS Depois": "0.00" if escolha.get("zerar_icms") else "",
            "Regra Aplicada": f"Classificação Manual - CFOP {novo_cfop}",
        })
        houve_alteracao_manual = True

    if houve_alteracao_manual:
        recalcular_totais_icms(root)

    caminho_manual = os.path.join(pasta_saida, os.path.basename(caminho_arquivo))
