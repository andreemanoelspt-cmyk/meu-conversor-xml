def iniciar_processamento(segmento):
    caminho_zip = selecionar_arquivos_zip()
    if not caminho_zip:
        return

    arquivos = extrair_xmls_do_zip(caminho_zip)
    if not arquivos:
        messagebox.showwarning("Aviso", "Nenhum XML foi encontrado dentro do arquivo ZIP.")
        return

    pasta_saida_final = selecionar_pasta()
    if not pasta_saida_final:
        return

    itens_pendentes = coletar_itens_pendentes(arquivos, segmento)
    escolhas_uso_consumo = {}

    if itens_pendentes:
        continuou = abrir_selecao_cfop_manual(itens_pendentes, escolhas_uso_consumo, janela)
        if not continuou:
            messagebox.showinfo("Cancelado", "Processamento cancelado pelo usuário.")
            return

    itens_supermercado = coletar_itens_supermercado_interestadual(arquivos, segmento)
    itens_construcao = coletar_itens_construcao_verificacao(arquivos, segmento)
    confirmacoes_supermercado = {}
    confirmacoes_construcao = {}

    if itens_supermercado:
        continuou = abrir_confirmacao_supermercado_interestadual(
            itens_supermercado,
            confirmacoes_supermercado,
            janela
        )
        if not continuou:
            messagebox.showinfo("Cancelado", "Processamento cancelado pelo usuário.")
            return

    if itens_construcao:
        continuou = abrir_confirmacao_supermercado_interestadual(
            itens_construcao,
            confirmacoes_construcao,
            janela
        )
        if not continuou:
            messagebox.showinfo("Cancelado", "Processamento cancelado pelo usuário.")
            return

    # ── Processamento paralelo com ThreadPoolExecutor ─────────────────
    pasta_temp_obj = tempfile.TemporaryDirectory()
    pasta_temp_modificados = pasta_temp_obj.name

    modificados = []
    xmls_modificados_paths = []
    lock = threading.Lock()
    progresso_atual = [0]
    total = len(arquivos)

    janela_prog, barra, status_var, percentual_var = criar_janela_progresso(janela, total)

    def processar_um(arquivo):
        """Worker: processa um XML e retorna (caminho_resultado, lista_modificados)."""
        mods_local = []
        try:
            path = ajustar_xml_com_escolhas(
                arquivo,
                pasta_temp_modificados,
                mods_local,
                segmento,
                escolhas_uso_consumo,
                confirmacoes_supermercado,
                confirmacoes_construcao,
            )
        except Exception as exc:
            path = None
            mods_local = []
            # registra erro sem travar a UI
            print(f"[ERRO] {os.path.basename(arquivo)}: {exc}")

        with lock:
            if path:
                xmls_modificados_paths.append(path)
            modificados.extend(mods_local)
            progresso_atual[0] += 1
            idx = progresso_atual[0]

        def _atualizar_ui():
            try:
                pct = int(idx / max(total, 1) * 100)
                status_var.set(f"Processando {idx}/{total}: {os.path.basename(arquivo)}")
                barra['value'] = idx
                percentual_var.set(f"{pct}%")
                janela_prog.update_idletasks()
            except Exception:
                pass

        janela_prog.after(0, _atualizar_ui)

    def _thread_worker():
        n_workers = max(1, min(os.cpu_count() or 4, 8, total))
        with concurrent.futures.ThreadPoolExecutor(max_workers=n_workers) as executor:
            list(executor.map(processar_um, arquivos))
        janela_prog.after(0, _finalizar)

    def _finalizar():
        try:
            janela_prog.destroy()
        except Exception:
            pass

        try:
            caminho_relatorio_resumo = os.path.join(pasta_saida_final, 'relatorio_modificados.xlsx')
            pd.DataFrame(modificados).to_excel(caminho_relatorio_resumo, index=False)
            caminho_zip_saida = criar_zip_xmls(xmls_modificados_paths, pasta_saida_final)
            caminho_relatorio_fiscal = gerar_relatorio_fiscal_xmls_modificados(
                xmls_modificados_paths, pasta_saida_final
            )
        except Exception as e:
            messagebox.showerror("Erro", f"Erro ao gerar relatórios:\n{e}")
            return
        finally:
            pasta_temp_obj.cleanup()

        msg = (
            '✅ Processamento finalizado!\n\n'
            f'ZIP dos XMLs: {caminho_zip_saida}\n'
            f'Relatório resumo: {caminho_relatorio_resumo}'
        )
        if caminho_relatorio_fiscal:
            msg += f'\nRelatório fiscal detalhado: {caminho_relatorio_fiscal}'
        messagebox.showinfo('Concluído', msg)

    t = threading.Thread(target=_thread_worker, daemon=True)
    t.start()


